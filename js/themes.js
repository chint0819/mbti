  const PRESET_THEMES = ['ラーメン', '犬', '猫', '戦国武将', '惑星', 'パン', 'カフェ', '文房具', '寿司ネタ', '妖怪'];

  /** テーマ文字列から決定的な小さいハッシュ値を作る(バリエーション選択用) */
  function themeHash(theme) {
    let h = 0;
    for (let i = 0; i < theme.length; i++) {
      h = (h * 31 + theme.charCodeAt(i)) >>> 0;
    }
    return h;
  }

  /**
   * タイプコード + テーマ → 表示用の結果オブジェクト
   */
  function buildResult(typeCode, theme) {
    const archetype = ARCHETYPES[typeCode];
    if (!archetype) {
      throw new Error('unknown type code: ' + typeCode);
    }
    const h = themeHash(theme);
    const modifier = archetype.modifiers[h % archetype.modifiers.length];
    const flavor = archetype.flavors[h % archetype.flavors.length].replaceAll('{theme}', theme);

    return {
      typeCode,
      theme,
      emoji: archetype.emoji,
      title: `${modifier}系${theme}`,
      archetypeName: archetype.name,
      catch: archetype.catch,
      desc: archetype.desc,
      strengths: archetype.strengths,
      advice: archetype.advice,
      flavor,
    };
  }

  /** 相性表示用: 相手タイプの名前とテーマ装飾 */
  function compatSummary(compatCode, theme) {
    const archetype = ARCHETYPES[compatCode];
    if (!archetype) return '';
    const h = themeHash(theme);
    const modifier = archetype.modifiers[h % archetype.modifiers.length];
    return `${archetype.emoji}「${modifier}系${theme}(${archetype.name})」タイプ。あなたにない視点を持ちつつ、大切にするものが通じ合う相手です。`;
  }

  global.DiagnosisThemes = { ARCHETYPES, PRESET_THEMES, buildResult, compatSummary, themeHash };
